#!/usr/bin/env python3
"""
Write a synthetic flight track log in the exact format the firmware emits.

    python make_test_log.py logs/synthetic_choreography.log

The point is to have the whole render pipeline working - layout, colours,
sync, output size, the ffmpeg-free mp4 path - BEFORE the one flight you get to
record. Debugging a plotting script with a real log means either flying again
or shipping a worse figure.

It flies the choreography: hover, a circle, then a climb-descend sequence with
continuous yaw, then land. The numbers are plausible for this airframe
(kF, CT, mass and the arm lengths come from FrameConventions.h) but they are
NOT a simulation - the rotor speeds are back-computed from the commanded
wrench through the same allocation the firmware uses, with lag and noise added
so the traces look like measurements rather than analytic curves.

Do not use the output for anything except exercising the renderer. It is
labelled SYNTHETIC in the header so a stray file cannot be mistaken for a
flight.
"""

import argparse
import math
import os

import numpy as np

# ---- airframe --------------------------------------------------------------
#
# Taken from the "#TRK" preamble of a REAL capture
# (logs/downlink_test_20260818_151530.log), not from FrameConventions.h. The
# firmware prints the values it is actually running, including the identified
# ones, so copying them from the log keeps the synthetic traces in the same
# numeric range as the real ones - which is the whole point of using this to
# lay out a figure before the flight.
MASS_KG = 0.45359237
KF = 1.170467e-06
KM = 1.170467e-08
ARM_X = 0.0815
ARM_Y = 0.08225
IXX, IYY, IZZ = 1.022860e-03, 1.004291e-03, 2.027151e-03
G = 9.80665

RATE_HZ = 50.0


def wrap180_deg(a):
    """Fold a heading in degrees into +/-180, as the firmware does."""
    return (a + 180.0) % 360.0 - 180.0


def choreography(t):
    """
    Return the commanded trajectory at time t.

    Phases, matching the flight plan:
        0-8 s     spool up, climb, let the holds capture
        8-38 s    one circle, 1.2 m radius, nose held forward
        38-62 s   climb and descend twice while yawing continuously
        62-70 s   descend and land
    """
    if t < 3.0:
        return dict(phase=0, x=0.0, y=0.0, z=0.0, yaw=0.0)
    if t < 8.0:
        s = (t - 3.0) / 5.0
        return dict(phase=2, x=0.0, y=0.0, z=0.50 * s, yaw=0.0)
    if t < 38.0:
        s = (t - 8.0) / 30.0
        a = 2.0 * math.pi * s
        return dict(phase=3, x=1.2 * math.sin(a), y=1.2 * (1 - math.cos(a)),
                    z=0.50, yaw=0.0)
    if t < 62.0:
        s = t - 38.0
        return dict(phase=3, x=0.0, y=0.0,
                    z=0.50 + 0.35 * math.sin(2 * math.pi * s / 12.0),
                    yaw=math.radians(30.0) * s)
    s = (t - 62.0) / 8.0
    return dict(phase=4, x=0.0, y=0.0, z=max(0.0, 0.50 * (1 - s)), yaw=
                math.radians(30.0) * 24.0)


def allocate(thrust, tx, ty, tz):
    """
    Wrench -> per-rotor omega, the same mapping RotorAllocator derives.

    M1 back-right, M2 back-left, M3 front-left, M4 front-right; {1,3} spin one
    way and {2,4} the other, which is why yaw torque adds to one diagonal and
    subtracts from the other.
    """
    u = np.empty(4)
    u[0] = thrust / 4 - ty / (4 * ARM_Y) + tx / (4 * ARM_X) - tz / (4 * KM / KF)
    u[1] = thrust / 4 + ty / (4 * ARM_Y) + tx / (4 * ARM_X) + tz / (4 * KM / KF)
    u[2] = thrust / 4 + ty / (4 * ARM_Y) - tx / (4 * ARM_X) - tz / (4 * KM / KF)
    u[3] = thrust / 4 - ty / (4 * ARM_Y) - tx / (4 * ARM_X) + tz / (4 * KM / KF)
    return np.sqrt(np.clip(u, 0.0, None) / KF)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", nargs="?", default="logs/synthetic_choreography.log")
    ap.add_argument("--duration", type=float, default=70.0)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    rng = np.random.default_rng(args.seed)
    n = int(args.duration * RATE_HZ)
    dt = 1.0 / RATE_HZ

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    fh = open(args.out, "w")

    w = fh.write
    w("SYNTHETIC LOG - generated by make_test_log.py, not a flight\n")
    w("#TRK v1 FPV2026 rotor-rate controller flight track log\n")
    w("#TRK rate_hz=%.1f deadband_rp=0.050 deadband_thr=0.080 "
      "deadband_yaw=0.060\n" % RATE_HZ)
    w("#TRK mass_kg=%.5f kf=%.6e km=%.6e armx_m=%.4f army_m=%.5f\n"
      % (MASS_KG, KF, KM, ARM_X, ARM_Y))
    w("#TRK ixx=%.6e iyy=%.6e izz=%.6e hover_omega=%.1f\n"
      % (IXX, IYY, IZZ, math.sqrt(MASS_KG * G / (4 * KF))))
    w("#TRK link=synthetic\n")
    w("#TRK hold states: 0=free 1=settling 2=held\n")
    w("#TRK angles in deg, rates in deg/s, positions in m, velocities in "
      "m/s, torque in N.m\n")
    w("#TRK wx = about +X = PITCH rate, wy = about +Y = ROLL rate, "
      "wz = about +Z = yaw rate, CCW positive\n")
    w("#TRKCOLS,"
      "t_ms,seq,dt_us,state,hold_alt,hold_xy,hold_hdg,"
      "armed,link,yaw_proven,flow_ok,range_ok,mag_ok,eskf_ok,eskf_att,"
      "sat_yaw_demand,sat_yaw_alloc,sat_rollpitch,rpm_mask,"
      "rc_thr,rc_roll,rc_pitch,rc_yaw,"
      "px,py,alt,px_t,py_t,alt_t,"
      "vbx,vby,vnx,vny,vz,vbx_t,vby_t,vz_t,"
      "roll,pitch,yaw,roll_d,pitch_d,yaw_t,"
      "wx,wy,wz,wx_t,wy_t,wz_t,"
      "thrust,tau_x,tau_y,tau_z,"
      "w1_sp,w2_sp,w3_sp,w4_sp,w1,w2,w3,w4,d1,d2,d3,d4,"
      "range,mag_yaw,flow_squal\n")

    # Rotor speeds lag their setpoint - that lag is exactly what the rotor
    # speed loop exists to close, and a log without it would make the
    # model-vs-measured panel look perfect for the wrong reason.
    omega = np.zeros(4)
    tau_rotor = 0.045          # s, first-order rotor spin-up
    prev = choreography(0.0)
    t0 = 4213                  # a non-zero millis(), like a real boot

    for k in range(n):
        t = k * dt
        c = choreography(t)
        nxt = choreography(t + dt)

        # Finite-difference the commanded path for velocity and acceleration.
        vx = (nxt["x"] - prev["x"]) / (2 * dt)
        vy = (nxt["y"] - prev["y"]) / (2 * dt)
        vz = (nxt["z"] - prev["z"]) / (2 * dt)
        ax = (nxt["x"] - 2 * c["x"] + prev["x"]) / (dt * dt)
        ay = (nxt["y"] - 2 * c["y"] + prev["y"]) / (dt * dt)
        az = (nxt["z"] - 2 * c["z"] + prev["z"]) / (dt * dt)
        prev = c

        # Tilt needed for the horizontal acceleration.
        pitch_d = math.atan2(ay, G + az)
        roll_d = -math.atan2(ax, G + az)
        yaw = c["yaw"]

        pitch = pitch_d + math.radians(rng.normal(0, 0.35))
        roll = roll_d + math.radians(rng.normal(0, 0.35))
        yaw_m = yaw + math.radians(rng.normal(0, 0.5))

        wz = math.radians(30.0) if 38.0 <= t < 70.0 else 0.0
        wx = (pitch - prev.get("_p", pitch)) / dt if False else \
            rng.normal(0, 0.05)
        wy = rng.normal(0, 0.05)

        thrust = MASS_KG * (G + az) / max(0.3, math.cos(roll) * math.cos(pitch))
        if c["phase"] == 0:
            thrust = 0.6

        tx = IXX * rng.normal(0, 0.8)
        ty = IYY * rng.normal(0, 0.8)
        tz = IZZ * (0.4 if 38.0 <= t < 62.0 else 0.0) + IZZ * rng.normal(0, 0.3)

        sp = allocate(thrust, tx, ty, tz)
        alpha = dt / (tau_rotor + dt)
        omega = omega + alpha * (sp - omega)
        meas = omega + rng.normal(0, 3.0, 4)

        dshot = np.clip(meas * 0.19, 0, 750).astype(int)

        armed = 1 if c["phase"] != 0 else 0
        airborne = c["z"] > 0.15
        hold_alt = 2 if (airborne and c["phase"] == 3) else (1 if airborne else 0)
        hold_xy = 2 if (airborne and t > 12.0) else 0
        hold_hdg = 2 if (airborne and t > 10.0) else 0

        # Sticks, reconstructed from what the pilot would have had to do.
        rc_thr = float(np.clip(vz / 0.6, -1, 1))
        rc_roll = float(np.clip(roll_d / math.radians(20), -1, 1))
        rc_pitch = float(np.clip(pitch_d / math.radians(20), -1, 1))
        rc_yaw = float(np.clip(wz / math.radians(120), -1, 1))

        rng_m = max(0.0, c["z"] * math.cos(roll) * math.cos(pitch)
                    + rng.normal(0, 0.006))
        mag_yaw = wrap180_deg(math.degrees(yaw) + rng.normal(0, 2.2))

        row = ["TRK", "%d" % (t0 + int(t * 1000)), "%d" % k,
               "%d" % int(rng.normal(1280, 60)),
               "%d" % c["phase"], "%d" % hold_alt, "%d" % hold_xy,
               "%d" % hold_hdg,
               "%d" % armed, "1", "1" if hold_hdg == 2 else "0",
               "1", "1", "1", "1", "1",
               "0", "0", "0", "F",
               "%.3f" % rc_thr, "%.3f" % rc_roll, "%.3f" % rc_pitch,
               "%.3f" % rc_yaw,
               "%.3f" % (c["x"] + rng.normal(0, 0.012)),
               "%.3f" % (c["y"] + rng.normal(0, 0.012)),
               "%.3f" % (c["z"] + rng.normal(0, 0.008)),
               "%.3f" % c["x"], "%.3f" % c["y"], "%.3f" % c["z"],
               "%.3f" % vx, "%.3f" % vy, "%.3f" % vx, "%.3f" % vy,
               "%.3f" % vz, "%.3f" % vx, "%.3f" % vy, "%.3f" % vz,
               # Headings are wrapped to +/-180, as the firmware wraps them.
               # An unwrapped yaw here would be a log the renderer never sees
               # in practice, and would hide a real scaling bug.
               "%.2f" % math.degrees(roll), "%.2f" % math.degrees(pitch),
               "%.2f" % wrap180_deg(math.degrees(yaw_m)),
               "%.2f" % math.degrees(roll_d), "%.2f" % math.degrees(pitch_d),
               "%.2f" % wrap180_deg(math.degrees(yaw)),
               "%.1f" % math.degrees(wx), "%.1f" % math.degrees(wy),
               "%.1f" % math.degrees(wz + rng.normal(0, 0.02)),
               "%.1f" % 0.0, "%.1f" % 0.0, "%.1f" % math.degrees(wz),
               "%.3f" % thrust, "%.5f" % tx, "%.5f" % ty, "%.5f" % tz]
        row += ["%.0f" % v for v in sp]
        row += ["%.0f" % v for v in meas]
        row += ["%d" % v for v in dshot]
        row += ["%.3f" % rng_m, "%.2f" % mag_yaw, "%d" % int(rng.normal(70, 6))]

        w(",".join(row) + "\n")

    w("#TRK end seq=%d dropped=0 dl_sent=%d dl_failed=0\n" % (n, n))
    fh.close()
    print("wrote %s  (%d rows, %.1f s)" % (args.out, n, args.duration))


if __name__ == "__main__":
    main()
